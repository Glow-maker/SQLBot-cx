import test from 'node:test'
import assert from 'node:assert/strict'
import { createProgress, receiveProgress, stepElapsed, endProgress, completeProgress, progressError, progressWarning, stageLabels } from '../src/views/chat/answer/chatProgress'

test('only explicit events complete stages; durations freeze and duplicate terminal events cannot regress', () => {
  const p = createProgress(0)
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'running', elapsedMs: 0 }, 0)
  assert.equal(stepElapsed(p.steps[0], 5000), 5000)
  assert.equal(p.steps[1].status, 'pending')
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'completed', elapsedMs: 2300 }, 2400)
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'running', elapsedMs: 0 }, 2500)
  assert.equal(stepElapsed(p.steps[0], 8000), 2300)
  assert.equal(p.steps[0].status, 'completed')
})
test('failure followed by finish stays expanded, with later stages unexecuted', () => {
  const p = createProgress(0)
  receiveProgress(p, { type: 'progress', stage: 'permission', status: 'running' }, 5)
  endProgress(p, 'failed', '没有权限', 20)
  completeProgress(p, false, 30)
  assert.equal(p.outcome, 'failed')
  assert.equal(p.steps[3].status, 'failed')
  assert.equal(p.steps[4].status, 'pending')
  assert.equal(p.expanded, true)
  assert.equal(p.endedAt, 20)
})
test('success needs all structured stages resolved; legacy backend does not fabricate a list', () => {
  const p = createProgress(0)
  receiveProgress(p, { type: 'progress', message: '正在查找表' }, 100)
  assert.equal(p.structured, false)
  assert.ok(p.steps.every(s => s.status === 'pending'))
  completeProgress(p, false, 200)
  assert.equal(p.outcome, 'succeeded')
  const incomplete = createProgress(0)
  receiveProgress(incomplete, { type: 'progress', stage: 'route', status: 'completed' })
  completeProgress(incomplete, false)
  assert.equal(incomplete.outcome, 'failed')
  const full = createProgress(0)
  for (const stage of Object.keys(stageLabels)) receiveProgress(full, { type: 'progress', stage, status: stage === 'result' ? 'skipped' : 'completed' }, 100)
  completeProgress(full, true, 200)
  assert.equal(full.outcome, 'succeeded')
  assert.equal(full.expanded, false)
  assert.match(full.message, /未找到/)
})
test('stopped reception freezes time and rejects late events; result loading failure overrides its completed row', () => {
  const p = createProgress(0)
  receiveProgress(p, { type: 'progress', stage: 'generate', status: 'running' }, 0)
  endProgress(p, 'stopped', '已停止接收', 5000)
  receiveProgress(p, { type: 'progress', stage: 'generate', status: 'completed' }, 10000)
  assert.equal(p.outcome, 'stopped')
  assert.equal(stepElapsed(p.steps[2], 10000), 5000)
  const q = createProgress(0)
  receiveProgress(q, { type: 'progress', stage: 'result', status: 'completed' }, 100)
  endProgress(q, 'failed', '加载失败', 200, 'result')
  assert.equal(q.steps[5].status, 'failed')
})
test('auth, service failure, missing permission and cross-source are distinct safe messages', () => {
  assert.match(progressError(JSON.stringify({ type: 'permission_denied', errorCode: 'authentication_expired' })), /登录/)
  assert.match(progressError({ type: 'permission_denied', reason: 'permission_service_unreachable' }), /服务暂不可用/)
  assert.match(progressError({ type: 'permission_denied' }), /没有相关/)
  assert.match(progressError({ type: 'cross_source_not_supported' }), /跨数据源/)
  assert.match(progressError({ type: 'query_timeout' }), /稍后重试/)
  assert.match(progressError({ reason: 'index_not_ready' }), /管理员同步/)
  assert.match(progressError({ reason: 'no_query_permission' }), /管理员授权/)
  assert.match(progressError({ reason: 'ambiguous_datasource' }), /补充数据源名称/)
})

test('long-wait and silent-stream hints do not invent progress or failure', () => {
  const p = createProgress(0)
  receiveProgress(p, { type: 'progress', stage: 'generate', status: 'running' }, 0)
  assert.equal(progressWarning(p, 14999), '')
  assert.match(progressWarning(p, 15000), /耗时较长/)
  assert.match(progressWarning(p, 30000), /暂未收到/)
  assert.equal(p.outcome, 'running')
  receiveProgress(p, { type: 'sql-result', content: 'partial output' }, 30001)
  assert.match(progressWarning(p, 30001), /耗时较长/)
  endProgress(p, 'stopped', '已停止接收', 31000)
  assert.equal(progressWarning(p, 60000), '')
})

test('compact progress reports real route details without inventing missing backend stages', () => {
  const p = createProgress(0)
  assert.equal(p.expanded, false)
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'running' }, 0)
  assert.deepEqual(p.steps[0].details, [])
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'running', detailStage: 'metadata', detailStatus: 'running', detailElapsedMs: 0 }, 10)
  assert.match(p.message, /加载可查询目录/)
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'running', detailStage: 'metadata', detailStatus: 'completed', detailElapsedMs: 90 }, 100)
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'running', detailStage: 'recall', detailStatus: 'running', detailElapsedMs: 0 }, 100)
  assert.match(p.message, /检索候选表/)
  assert.equal(stepElapsed(p.steps[0].details[0], 500), 90)
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'running', detailStage: 'metadata', detailStatus: 'running', detailElapsedMs: 0 }, 150)
  assert.equal(p.steps[0].details[0].status, 'completed')
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'running', detailStage: 'unknown', detailStatus: 'running' }, 160)
  assert.equal(p.steps[0].details.length, 2)
  endProgress(p, 'failed', '检索失败', 200)
  assert.equal(p.steps[0].details[1].status, 'failed')
  assert.equal(stepElapsed(p.steps[0].details[1], 1000), 100)
  assert.equal(p.expanded, true)
})

test('stopped route details freeze and reject late substage completion', () => {
  const p = createProgress(0)
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'running', detailStage: 'selection', detailStatus: 'running' }, 0)
  endProgress(p, 'stopped', '已停止接收', 500)
  receiveProgress(p, { type: 'progress', stage: 'route', status: 'completed', detailStage: 'selection', detailStatus: 'completed', detailElapsedMs: 800 }, 800)
  assert.equal(p.steps[0].details[0].status, 'pending')
  assert.equal(stepElapsed(p.steps[0].details[0], 1000), 500)
})
